const makeMonthly = (base: number, trend: 'up' | 'flat' | 'down' = 'flat') => {
  const months = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
  return months.map((m, i) => {
    const factor = trend === 'up' ? 1 + i * 0.04 : trend === 'down' ? 1 - i * 0.02 : 1;
    const noise = 0.85 + Math.random() * 0.3;
    return { month: m, procedures: Math.round(base * factor * noise), revenue: Math.round(base * factor * noise * 1850) };
  });
};

